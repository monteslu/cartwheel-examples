// Writes pugball's floodlight profile (assets/lights/flood.ies), an IES photometric file made here from code (no
// fixture's data): the night ring's lamps under the roof. An asymmetric sports flood: its beam reaches further out
// over the pitch (twist 0, the light's up when it is aimed down from the roof) than back toward the wall it hangs
// over (twist 180), an even pool with a hot spot out over the pitch and a firm cut-off. Mirrored left to right by the loader.
//
//   node games/pugball/tools/make-ies.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const D = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'lights');
mkdirSync(D, { recursive: true });
const g = (x, c, w) => Math.exp(-((x - c) * (x - c)) / (2 * w * w));
const step = (a, b, s) => { const o = []; for (let v = a; v <= b; v += s) o.push(v); return o; };
const ver = step(0, 90, 2.5), hor = step(0, 180, 15);
const cd = (v, h) => {
  const out = 0.5 + 0.5 * Math.cos((h * Math.PI) / 180); // 1 toward the far side of the pitch, 0 toward the wall
  const edge = 34 + 10 * out; // the cut-off: 34 degrees toward the wall, 44 out over the pitch
  const cut = 1 / (1 + Math.exp((v - edge) / 2));
  const throwPeak = 8 + 14 * out; // the hot spot sits further out than the aim
  return 1000 * (0.86 + 0.14 * g(v, throwPeak, 8)) * cut + 30 * g(v, edge + 8, 10);
};
const rows = hor.map((h) => ver.map((v) => Math.max(0, Math.round(cd(v, h)))).join(' '));
const text = ['IESNA:LM-63-2002', '[TEST] pugball floodlight', '[OTHER] generated by games/pugball/tools/make-ies.mjs, CC0', 'TILT=NONE',
  `1 1000 1 ${ver.length} ${hor.length} 1 2 0 0 0`, '1 1 100', ver.join(' '), hor.join(' '), ...rows, ''].join('\n');
writeFileSync(join(D, 'flood.ies'), text);
console.log(`wrote assets/lights/flood.ies: ${ver.length} x ${hor.length} angles`);
