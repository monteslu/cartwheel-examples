// Writes derby's floodlight profile (assets/lights/flood.ies), an IES photometric file made here from code (no
// fixture's data): what the four corner floods throw. A bank of eight lamps behind one reflector: an even
// pool with a brighter ring where the reflector adds (about 27 degrees out), a firm cut-off near 40 degrees and a little spill past it, wider across
// the bank (twist 90) than up and down (twist 0). Mirrored from one quadrant by the loader.
//
//   node games/derby/tools/make-ies.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const D = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'lights');
mkdirSync(D, { recursive: true });
const g = (x, c, w) => Math.exp(-((x - c) * (x - c)) / (2 * w * w));
const step = (a, b, s) => { const o = []; for (let v = a; v <= b; v += s) o.push(v); return o; };
const ver = step(0, 90, 2.5), hor = step(0, 90, 15);
const cd = (v, h) => {
  const across = Math.sin((h * Math.PI) / 180) ** 2; // 0 up and down the bank, 1 across it
  const t = v / (1 + 0.3 * across); // the beam a third wider across
  const cut = 1 / (1 + Math.exp((t - 38) / 1.8)); // the reflector's edge
  return 1000 * (0.9 + 0.04 * g(t, 0, 8) + 0.1 * g(t, 27, 6)) * cut + 40 * g(t, 48, 10);
};
const rows = hor.map((h) => ver.map((v) => Math.max(0, Math.round(cd(v, h)))).join(' '));
const text = ['IESNA:LM-63-2002', '[TEST] derby floodlight', '[OTHER] generated by games/derby/tools/make-ies.mjs, CC0', 'TILT=NONE',
  `1 1000 1 ${ver.length} ${hor.length} 1 2 0 0 0`, '1 1 100', ver.join(' '), hor.join(' '), ...rows, ''].join('\n');
writeFileSync(join(D, 'flood.ies'), text);
console.log(`wrote assets/lights/flood.ies: ${ver.length} x ${hor.length} angles`);
